#!/usr/bin/env bash
# DEV/TEST ONLY. Generates a throwaway PKI that imitates the shape of a DoD CAC/PIV deployment so the Keel X.509 sign-in
# configuration can be tested without real cards: a test CA, a Keycloak server certificate, and client certificates for
# the cases the tests must tell apart. NOTHING made here is a real credential and nothing here may be trusted in
# production: every subject carries "KEEL DEV TEST PKI NOT FOR PRODUCTION" and the output directory gets a warning file.
# Never import the test CA into a production Keycloak truststore.
#
# Usage: scripts/idp/generate-test-pki.sh <output-dir> [--force]
# Needs: bash, openssl (1.1.1 or newer; OpenSSL 3/4 fine). Runs offline.
#
# Output (all PEM unless noted):
#   ca.crt ca.key               test root CA          crl.pem (DER: crl.der)   CRL naming the revoked client certificate
#   server.crt server.key       Keycloak TLS server certificate (SAN localhost, 127.0.0.1)
#   alice.p12                   VALID  CAC-style client certificate for the Keel dev user alice (EDIPI 1000000001)
#   bob.p12                     VALID  second user (EDIPI 1000000002), shows two users do not collide
#   unknown.p12                 valid certificate from the trusted CA whose EDIPI belongs to no Keel user
#   expired.p12                 certificate of EDIPI 1000000001 whose validity ended before today
#   revoked.p12                 certificate of EDIPI 1000000001 that is valid by date but listed in crl.pem
#   untrusted.p12               certificate of EDIPI 1000000001 issued by a different CA that Keel never trusts
#   untrusted-ca.crt            that other CA (only for tests that prove the truststore rejects it)
# PKCS#12 password for every .p12: keel-dev-test
set -euo pipefail

out="${1:-}"; force="${2:-}"
[ -n "$out" ] || { echo "usage: $0 <output-dir> [--force]" >&2; exit 2; }
if [ -e "$out" ] && [ -n "$(ls -A "$out" 2>/dev/null)" ] && [ "$force" != "--force" ]; then
  echo "refusing to write into non-empty '$out' (pass --force to replace)" >&2; exit 2
fi
rm -rf "$out"; mkdir -p "$out"; out="$(cd "$out" && pwd)"
P12PASS="keel-dev-test"
ORG="KEEL DEV TEST PKI NOT FOR PRODUCTION"

cat > "$out/README-DEV-ONLY.txt" <<TXT
These files were generated by scripts/idp/generate-test-pki.sh for tests of the Keel CAC/PIV sign-in configuration.
They are NOT real credentials, they are NOT secret (the CA key is deliberately kept beside them) and the CA must never
be trusted by a production system.
TXT

# --- a small openssl CA database so 'openssl ca' can back-date certificates and produce a CRL
mkca() { # dir cn
  mkdir -p "$1/newcerts"; : > "$1/index.txt"; echo 1000 > "$1/serial"; echo 1000 > "$1/crlnumber"
  openssl req -x509 -newkey rsa:3072 -sha256 -nodes -days 3650 -keyout "$1/ca.key" -out "$1/ca.crt" \
    -subj "/O=$ORG/OU=TEST CA/CN=$2" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
  cat > "$1/ca.cnf" <<CNF
[ca]
default_ca = CA_default
[CA_default]
dir = $1
database = \$dir/index.txt
new_certs_dir = \$dir/newcerts
serial = \$dir/serial
crlnumber = \$dir/crlnumber
certificate = \$dir/ca.crt
private_key = \$dir/ca.key
default_md = sha256
default_crl_days = 30
policy = policy_any
unique_subject = no
copy_extensions = none
[policy_any]
commonName = supplied
organizationName = optional
organizationalUnitName = optional
CNF
}

issue_client() { # cadir name edipi last first [startdate enddate]
  local ca="$1" name="$2" edipi="$3" last="$4" first="$5" start="${6:-}" end="${7:-}"
  # CAC convention: CN=LAST.FIRST.MIDDLE.EDIPI. The PIV authentication certificate also carries the UPN EDIPI@mil in the SAN
  # (otherName 1.3.6.1.4.1.311.20.2.3) and an e-mail address.
  local cn="${last}.${first}.T.${edipi}" cnf="$out/$name.cnf"
  cp "$ca/ca.cnf" "$cnf"
  local lfirst lowlast; lfirst=$(echo "$first" | tr A-Z a-z); lowlast=$(echo "$last" | tr A-Z a-z)
  cat >> "$cnf" <<CNF
[client_ext]
basicConstraints = CA:FALSE
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid
keyUsage = critical,digitalSignature
extendedKeyUsage = clientAuth,1.3.6.1.4.1.311.20.2.2
subjectAltName = @client_san
[client_san]
otherName.1 = 1.3.6.1.4.1.311.20.2.3;UTF8:${edipi}@mil
email.1 = ${lfirst}.${lowlast}@keel.test
CNF
  openssl req -newkey rsa:3072 -nodes -keyout "$out/$name.key" -out "$out/$name.csr" -subj "/O=$ORG/OU=TEST PKI/CN=$cn" 2>/dev/null
  local dates=(); [ -n "$start" ] && dates=(-startdate "$start" -enddate "$end") || dates=(-days 365)
  openssl ca -batch -config "$cnf" -extensions client_ext "${dates[@]}" -in "$out/$name.csr" -out "$out/$name.crt" -notext 2>/dev/null
  openssl pkcs12 -export -inkey "$out/$name.key" -in "$out/$name.crt" -certfile "$ca/ca.crt" -out "$out/$name.p12" -passout "pass:$P12PASS" 2>/dev/null
  rm -f "$out/$name.csr" "$cnf"
}

mkca "$out/ca" "KEEL DEV TEST ROOT CA"
cp "$out/ca/ca.crt" "$out/ca.crt"; cp "$out/ca/ca.key" "$out/ca.key"

# --- server certificate for Keycloak
openssl req -newkey rsa:3072 -nodes -keyout "$out/server.key" -out "$out/server.csr" -subj "/O=$ORG/OU=TEST PKI/CN=localhost" 2>/dev/null
cp "$out/ca/ca.cnf" "$out/server.cnf"
cat >> "$out/server.cnf" <<CNF
[server_ext]
basicConstraints = CA:FALSE
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid
keyUsage = critical,digitalSignature,keyEncipherment
extendedKeyUsage = serverAuth
subjectAltName = DNS:localhost,IP:127.0.0.1
CNF
openssl ca -batch -config "$out/server.cnf" -extensions server_ext -days 365 -in "$out/server.csr" -out "$out/server.crt" -notext 2>/dev/null
rm -f "$out/server.csr"

# --- client certificates (date-valid unless noted). Dates for 'openssl ca' are YYMMDDHHMMSSZ.
now_utc="$(date -u +%y%m%d%H%M%SZ)"
past_start="$(date -u -d '-40 days' +%y%m%d%H%M%SZ 2>/dev/null || date -u -v-40d +%y%m%d%H%M%SZ)"
past_end="$(date -u -d '-10 days' +%y%m%d%H%M%SZ 2>/dev/null || date -u -v-10d +%y%m%d%H%M%SZ)"
issue_client "$out/ca" alice   1000000001 ENGINEER ALICE
issue_client "$out/ca" bob     1000000002 BUILDER  BOB
issue_client "$out/ca" unknown 1999999999 NOBODY   UNKNOWN
issue_client "$out/ca" expired 1000000001 ENGINEER ALICE "$past_start" "$past_end"
issue_client "$out/ca" revoked 1000000001 ENGINEER ALICE
openssl ca -batch -config "$out/ca/ca.cnf" -revoke "$out/revoked.crt" -crl_reason keyCompromise 2>/dev/null
openssl ca -batch -config "$out/ca/ca.cnf" -gencrl -out "$out/crl.pem" 2>/dev/null
openssl crl -in "$out/crl.pem" -outform DER -out "$out/crl.der"

# --- a second CA that nobody trusts, issuing a certificate with a valid-looking identity
mkca "$out/untrusted-ca" "KEEL DEV TEST UNTRUSTED CA"
cp "$out/untrusted-ca/ca.crt" "$out/untrusted-ca.crt"
issue_client "$out/untrusted-ca" untrusted 1000000001 ENGINEER ALICE

# --- leave only what a consumer needs; the CA private keys stay (dev only), the CA databases do not
rm -rf "$out/ca" "$out/untrusted-ca" "$out"/*.cnf
chmod 600 "$out"/*.key
echo "Test PKI written to $out (DEV ONLY; PKCS#12 password: $P12PASS)"
