using System.Text;
using System.Text.Json;
using Keel.Core;
using Keel.Migration.Sources;

namespace Keel.Migration.Mapping;

/// <summary>
/// Generates a starter mapping file from a source inventory: every source state, unit, type, user and property found in the package is listed
/// for a decision. Obvious matches are pre-filled; everything else is left EMPTY so that validation fails until a person decides (the template never
/// guesses a markings rule: the section lists candidate properties in comments only).
/// </summary>
public static class MappingTemplate
{
    private static readonly string[] MarkingHints = ["itar", "export", "eccn", "usml", "distribution", "program", "project", "security", "classif", "cui", "ear", "fouo", "restrict", "control"];

    public static string Generate(SourceInventory inv)
    {
        var sb = new StringBuilder();
        string Q(string s) => JsonSerializer.Serialize(s);
        sb.AppendLine("// Starter mapping generated by `keel-import map-template`. Every empty \"\" value needs a decision before the mapping validates.");
        sb.AppendLine("// Reference: docs/migration/mapping-reference.md. Comments are allowed in this file.");
        sb.AppendLine("{");
        sb.AppendLine("  \"version\": 1,");
        sb.AppendLine($"  \"name\": {Q("starter for " + (inv.SourceSystem.Length == 0 ? "source" : inv.SourceSystem))},");
        sb.AppendLine("  \"auditGranularity\": \"batch\",");

        void Map(string name, IEnumerable<string> keys, Func<string, string> guess, string indent = "  ", string comment = "", string? extra = null, bool last = false)
        {
            sb.AppendLine($"{indent}// {comment}");
            sb.Append($"{indent}{Q(name)}: {{ ");
            if (extra is not null) sb.Append(extra).Append(", ");
            sb.AppendLine("\"map\": {");
            var list = keys.Where(k => k != "(none)").ToList();
            for (var i = 0; i < list.Count; i++) sb.AppendLine($"{indent}    {Q(list[i])}: {Q(guess(list[i]))}{(i < list.Count - 1 ? "," : "")}");
            sb.AppendLine($"{indent}  }} }}{(last ? "" : ",")}");
        }

        sb.AppendLine("  // Source lifecycle state -> Keel state (InWork, UnderReview, Released, Obsolete). Unknown states are errors unless \"default\" is set.");
        sb.AppendLine("  \"lifecycle\": { \"states\": {");
        var states = inv.ItemStates.Keys.Concat(inv.DocumentStates.Keys).Distinct().Order(StringComparer.Ordinal).ToList();
        for (var i = 0; i < states.Count; i++) sb.AppendLine($"    {Q(states[i])}: {Q(GuessState(states[i]))}{(i < states.Count - 1 ? "," : "")}");
        sb.AppendLine("  } },");
        sb.AppendLine("  \"revisions\": { \"order\": \"auto\", \"policy\": \"sequence\", \"explicit\": {} },");
        sb.AppendLine("  \"assemblyWhenHasBom\": true,");
        Map("partTypes", inv.ItemTypes.Keys, GuessPartType, comment: "Source item type -> Assembly, Component, Standard, RawMaterial.", extra: "\"default\": \"Component\"");
        Map("partSources", inv.Sources.Keys, s => s.StartsWith("buy", StringComparison.OrdinalIgnoreCase) || s.StartsWith("purch", StringComparison.OrdinalIgnoreCase) ? "Buy" : s.StartsWith("make", StringComparison.OrdinalIgnoreCase) ? "Make" : "", comment: "Source make/buy -> Make or Buy.", extra: "\"default\": \"Make\"");
        Map("units", inv.Units.Keys, GuessUnit, comment: $"Source unit -> one of: {string.Join(", ", UnitsOfMeasure.All)}. Unknown units are errors.");
        Map("documentTypes", inv.DocumentTypes.Keys, GuessDocType, comment: "Source document type -> Specification, Drawing, CAD, Report, Procedure, Other.", extra: "\"default\": \"Other\"");

        sb.AppendLine("  // Source property -> Keel attribute definition for parts (see plm.attribute_definition). Unlisted properties are kept in legacy_properties and reported.");
        sb.AppendLine("  \"attributes\": { \"keepUnmapped\": true, \"map\": {");
        var props = inv.Properties.Keys.Order(StringComparer.Ordinal).ToList();
        sb.AppendLine("    // Properties found in the source (count): " + string.Join(", ", props.Take(60).Select(p => $"{p} ({inv.Properties[p]})")) + (props.Count > 60 ? ", ..." : ""));
        sb.AppendLine("  } },");

        sb.AppendLine("  // Source user -> Keel username. Users not listed use \"default\" (flagged in the report); remove \"default\" to make unmapped users errors.");
        sb.AppendLine("  \"users\": { \"default\": \"migration\", \"map\": {");
        var users = inv.Users.Keys.Where(u => u != "(none)").Order(StringComparer.Ordinal).ToList();
        for (var i = 0; i < users.Count; i++) sb.AppendLine($"    {Q(users[i])}: \"\"{(i < users.Count - 1 ? "," : "")}");
        sb.AppendLine("  } },");

        sb.AppendLine("  // MARKINGS. Fail closed: an object that no rule gives an export jurisdiction is an error unless \"defaultMarkings\" is set.");
        sb.AppendLine("  // Properties that look like markings inputs: " + (props.Where(p => MarkingHints.Any(h => p.Contains(h, StringComparison.OrdinalIgnoreCase))).DefaultIfEmpty("(none found)").Aggregate((a, b) => a + ", " + b)));
        sb.AppendLine("  // Example rule (copy, edit, then remove this comment):");
        sb.AppendLine("  //   { \"name\": \"itar-flag\", \"when\": { \"property\": \"ITAR\", \"equals\": \"Y\" },");
        sb.AppendLine("  //     \"set\": { \"exportJurisdiction\": \"Itar\", \"usmlCategory\": \"XI(d)\", \"cui\": [\"EXPT\"], \"distributionStatement\": \"D\",");
        sb.AppendLine("  //             \"controllingOffice\": \"...\", \"distributionReason\": \"...\", \"programFromProperty\": \"Project\", \"owningOrg\": \"...\" } }");
        sb.AppendLine("  \"markings\": { \"rules\": [] },");

        sb.AppendLine("  // Change objects: source type -> PR, ECR, ECN; per Keel type, source state -> Keel state. Class: I or II.");
        var changeTypes = inv.ChangeTypes.Keys.Where(t => t != "(none)").Order(StringComparer.Ordinal).ToList();
        var changeStates = inv.ChangeStates.Keys.Where(t => t != "(none)").Order(StringComparer.Ordinal).ToList();
        sb.AppendLine("  // Source change types: " + string.Join(", ", changeTypes) + "; source change states: " + string.Join(", ", changeStates));
        sb.AppendLine("  \"changes\": { \"types\": { \"map\": {} }, \"states\": {}, \"classMap\": {}, \"defaultPriority\": \"Medium\" },");
        sb.AppendLine("  \"classification\": { \"load\": false },");
        sb.AppendLine("  \"limits\": { \"maxPropertyValueChars\": 65536, \"maxLegacyJsonChars\": 1000000, \"maxUsagesPerIteration\": 5000 }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string GuessState(string s)
    {
        var l = s.ToLowerInvariant();
        if (l.Contains("review", StringComparison.Ordinal)) return "UnderReview";
        if (l.Contains("release", StringComparison.Ordinal) || l == "approved") return "Released";
        if (l.Contains("obsol", StringComparison.Ordinal) || l.Contains("retire", StringComparison.Ordinal) || l.Contains("supersed", StringComparison.Ordinal) || l.Contains("cancel", StringComparison.Ordinal)) return "Obsolete";
        if (l.Contains("work", StringComparison.Ordinal) || l.Contains("draft", StringComparison.Ordinal) || l.Contains("prelim", StringComparison.Ordinal) || l.Contains("design", StringComparison.Ordinal)) return "InWork";
        return "";
    }

    private static string GuessPartType(string s)
    {
        var l = s.ToLowerInvariant();
        if (l.Contains("assem", StringComparison.Ordinal)) return "Assembly";
        if (l.Contains("material", StringComparison.Ordinal) || l.Contains("raw", StringComparison.Ordinal)) return "RawMaterial";
        if (l.Contains("standard", StringComparison.Ordinal)) return "Standard";
        return "Component";
    }

    private static string GuessDocType(string s)
    {
        var l = s.ToLowerInvariant();
        foreach (var t in new[] { "Specification", "Drawing", "CAD", "Report", "Procedure" })
            if (l.Contains(t.ToLowerInvariant(), StringComparison.Ordinal)) return t;
        return "Other";
    }

    private static string GuessUnit(string s)
    {
        if (UnitsOfMeasure.IsValid(s)) return s;
        return s.Trim().ToLowerInvariant() switch
        {
            "each" or "ea" or "pcs" or "piece" or "pieces" or "count" => "EA",
            "millimeter" or "millimeters" or "millimetre" => "mm", "centimeter" => "cm", "meter" or "metre" => "m", "inch" or "inches" => "in", "foot" or "feet" => "ft",
            "gram" or "grams" => "g", "kilogram" or "kilograms" => "kg", "pound" or "pounds" => "lb", "liter" or "litre" => "L", "milliliter" => "mL", "gallon" => "gal", "set" or "kit" => "SET",
            _ => "",
        };
    }
}
